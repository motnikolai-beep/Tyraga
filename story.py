class Story:
    """Движок кампании: сцены, проверки, последствия, концовки."""

    def __init__(self, world):
        self.w = world
        self.s = world.s["story"]
        self.s.setdefault("scene", "intro")
        self.s.setdefault("flags", {})
        self.s.setdefault("entered", [])
        self.s.setdefault("log", [])
        self.s.setdefault("checks", {"ok": 0, "fail": 0})
        self.s.setdefault("ending", None)
        self.s.setdefault("objective", "")

    # -------------------------------------------------------------- доступ
    def scene(self):
        return SCENES.get(self.s["scene"])

    def finished(self):
        return bool(self.s.get("ending"))

    def where(self):
        scn = self.scene()
        return scn.get("where") if scn else None

    def here(self):
        """Сцена доступна в текущей локации?"""
        scn = self.scene()
        if not scn or self.finished():
            return False
        w = scn.get("where")
        return w is None or LOC_INDEX.get(w) == self.w.s["loc"]

    def at_ready(self):
        """Сцена доступна и по времени (шконка — только ночью и т.п.)."""
        if not self.here():
            return False
        scn = self.scene()
        if scn["id"] == "first_night" and not self.w.is_night():
            return False
        if scn["id"] == "visit_mama" and self.w.s["visit"].get("used"):
            return False
        return True

    def enter(self):
        """Применяет эффекты входа в сцену (один раз) и возвращает сцену."""
        scn = self.scene()
        if not scn:
            return None
        if scn["id"] not in self.s["entered"]:
            self.s["entered"].append(scn["id"])
            self.s["objective"] = scn.get("objective", self.s["objective"])
            eff = scn.get("enter")
            if eff:
                self.apply(eff)
        return scn

    # -------------------------------------------------------------- проверки
    def stat(self, key):
        if key == "hon":
            return self.w.stats()["wis"]
        if key == "gold":
            return self.w.s["rub"] // 20
        return self.w.stats().get(key, 3)

    def roll(self, key, dc):
        bonus = self.stat(key)
        d = self.w.rng.randint(1, 20)
        total = d + bonus
        ok = (d == 20) or (total >= dc and d != 1)
        crit = "20" if d == 20 else "1" if d == 1 else ""
        self.s["checks"]["ok" if ok else "fail"] += 1
        names = {"wis": "Мудрость", "cha": "Харизма", "cun": "Хитрость", "str": "Сила", "hon": "Честность"}
        text = "Проверка: %s · d20=%d + %d = %d против %d — %s%s" % (
            names.get(key, key), d, bonus, total, dc, "успех" if ok else "провал",
            " (крит!)" if crit == "20" else " (крит-провал)" if crit == "1" else "")
        return ok, text, {"die": d, "bonus": bonus, "total": total, "dc": dc, "ok": ok}

    # -------------------------------------------------------------- выбор
    def choose(self, index):
        scn = self.scene()
        if not scn:
            raise ValueError("Нет активной сцены")
        choices = self.available(scn)
        if not 0 <= index < len(choices):
            raise ValueError("Нет такого варианта")
        ch = choices[index]
        result = {"check": None, "ok": True, "effects": [], "ending": None, "next": None}
        if "check" in ch:
            key, dc = ch["check"]
            ok, text, info = self.roll(key, dc)
            result.update(check=text, ok=ok, info=info)
            eff = ch.get("ok" if ok else "fail", {})
        else:
            eff = ch.get("ok", {})
        notes = self.apply(eff)
        result["effects"] = notes
        nxt = eff.get("next")
        if nxt:
            self.goto(nxt)
            result["next"] = nxt
        if eff.get("ending"):
            self.end(eff["ending"])
            result["ending"] = eff["ending"]
        self.s["log"].append({"scene": scn["id"], "choice": ch.get("text", ""),
                              "ok": result["ok"], "check": result["check"], "day": self.w.s["day"]})
        self.s["log"] = self.s["log"][-200:]
        return result

    def available(self, scn=None):
        scn = scn or self.scene()
        out = []
        for ch in scn.get("choices", []):
            need = ch.get("need")
            if need is not None and not need(self.w):
                continue
            out.append(ch)
        return out

    # -------------------------------------------------------------- эффекты
    def apply(self, eff):
        w, s = self.w, self.w.s
        notes = []
        if not eff:
            return notes
        for key, val in eff.items():
            if key in ("next",):
                continue
            if key == "respect" and val:
                if val > 0:
                    w.rise(val, "сюжет")
                else:
                    s["respect"] = clamp(s["respect"] + val, 0, 100)
                notes.append("Уважение %+d" % val)
            elif key == "karma" and isinstance(val, dict):
                for d, v in val.items():
                    s["karma"][d] = clamp(s["karma"].get(d, 0) + v)
                notes.append("Карма: " + ", ".join("%s %+d" % (d, v) for d, v in val.items()))
            elif key == "karma_clean" and val:
                cleaned = 0
                for d in DIMS_ORDER:
                    if s["karma"][d] < 0:
                        step = min(-s["karma"][d], int(val))
                        s["karma"][d] += step
                        cleaned += step
                notes.append("Карма очищена на %d" % cleaned)
            elif key == "item" and isinstance(val, dict):
                for it, n in val.items():
                    if n < 0 and w.inv(it) < -n:
                        notes.append("Не хватило: " + ITEMS.get(it, {"name": it})["name"])
                        continue
                    w.add(it, n)
                    notes.append("%s %+d" % (ITEMS.get(it, {"name": it})["name"], n))
            elif key == "rub" and val:
                s["rub"] = max(0, s["rub"] + val)
                notes.append("Рубли %+d" % val)
            elif key == "rel" and isinstance(val, dict):
                for k, v in val.items():
                    s["relations"][k] = clamp(s["relations"].get(k, 0) + v)
                notes.append("Отношения изменились")
            elif key in ("hp", "stamina", "food") and val:
                limits = {"hp": (1, s["hp_max"]), "stamina": (0, s["stamina_max"]), "food": (0, 100)}
                lo, hi = limits[key]
                s[key] = max(lo, min(hi, s[key] + val))
            elif key == "time" and val:
                w.advance(val, "сюжет")
            elif key == "flag" and isinstance(val, dict):
                for f, v in val.items():
                    s["story"]["flags"][f] = v
            elif key == "unlock" and isinstance(val, dict):
                for f, v in val.items():
                    s["flags"][f] = v
                    s["story"]["flags"][f] = v
            elif key == "drop":
                w.humiliate(val, strong=True)
                notes.append("Тебя опустили")
            elif key == "humiliate":
                w.humiliate(val, strong=False)
            elif key == "prayer":
                try:
                    w.pray()
                except ValueError as e:
                    notes.append(str(e))
            elif key == "training_str" and val:
                s["training"]["str"] = min(20, s["training"]["str"] + val)
                notes.append("Сила +%d" % val)
            elif key == "toast" and val:
                w.toast(val, "story")
                notes.append(val)
            elif key == "objective" and val:
                s["story"]["objective"] = val
            elif key in ("stamina", "food"):
                pass
        return notes

    def goto(self, scene_id):
        if scene_id not in SCENES:
            raise ValueError("Нет сцены " + str(scene_id))
        self.s["scene"] = scene_id
        self.enter()

