def _ok(w,tr):
    from core import C
    c=C(w);s=w.s
    if s['day']<tr.get('day',0):return False
    if 'after' in tr and any(a not in c['done'] for a in tr['after']):return False
    if 'flag' in tr and not c['flags'].get(tr['flag']):return False
    if 'noflag' in tr and c['flags'].get(tr['noflag']):return False
    if 'caste_min' in tr and c['caste']<tr['caste_min']:return False
    if 'caste_max' in tr and c['caste']>tr['caste_max']:return False
    if 'alive' in tr and tr['alive'] in c['ousted']:return False
    if 'flags_all' in tr and not all(c['flags'].get(f) for f in tr['flags_all']):return False
    if 'noflags' in tr and any(c['flags'].get(f) for f in tr['noflags']):return False
    if 'rel' in tr and any(s['relations'].get(k,0)<v for k,v in tr['rel'].items()):return False
    if 'honor_min' in tr and s['karma']['honor']<tr['honor_min']:return False
    if 'ousted_max' in tr and len(c['ousted'])>tr['ousted_max']:return False
    if 'dig_min' in tr and s['dig']<tr['dig_min']:return False
    return True

def available(w,loc=None):
    from core import C
    L=w.s['loc'] if loc is None else loc;c=C(w)
    for sid,sc in SCENES.items():
        if not sc['story'] or sid in c['done']:continue
        tr=sc['trig']
        if 'loc' in tr and tr['loc']!=L:continue
        if _ok(w,tr):yield sid

