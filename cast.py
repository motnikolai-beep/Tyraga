CASES=('nom','gen','dat','acc','ins')

def form(k,case='nom'):
    """Имя героя k в падеже case. Незнакомый id возвращается как есть: текст не должен падать из-за нового героя."""
    row=FORMS.get(k)
    return row[CASES.index(case)] if row else str(k)
def nom(k):return form(k,'nom')
def gen(k):return form(k,'gen')
def dat(k):return form(k,'dat')
def acc(k):return form(k,'acc')
def ins(k):return form(k,'ins')
def sex(k):return FORMS[k][5] if k in FORMS else 'm'
def g(k,m,f):
    """Слово по полу героя: g('gen','сказал','сказала') -> 'сказала'."""
    return f if sex(k)=='f' else m
def forms(k,prefix):
    """Все падежи героя для подстановки в текст сцены: {a}, {a_gen}, {a_dat}, {a_acc}, {a_ins}."""
    out={prefix+('' if c=='nom' else '_'+c):form(k,c) for c in CASES}
    out[prefix+'_id']=k
    return out

