def journal(w):
    c=core.C(w);rows=[]
    for k in c['ousted']:
        if k not in w.npcs:continue
        r=c['ex'].get(k) or {};st=r.get('revenge');name=w.npcs[k]['name'];home=w.npcs[k]['home']
        if st in('due','fight'):t='⚔ зовёт на разборку %s сегодня до отбоя'%cast.place_in(home)
        elif r.get('peace'):t='помирились'
        elif st=='won':t='реванш отбит, больше не полезет'
        elif st in('off','never'):t=cast.g(k,'смирился','смирилась')
        elif r.get('will'):t=cast.g(k,'затаил','затаила')+' обиду: ждите реванша'
        else:t='держится в стороне'
        rows.append('%s, %s: %s'%(name,label(k),t))
    for k,r in c['ex'].items():
        if r.get('revenge')=='back' and core.in_power(w,k):rows.append('%s: %s себе %s'%(w.npcs[k]['name'],cast.g(k,'вернул','вернула'),EX[k]['took']))
    return rows

