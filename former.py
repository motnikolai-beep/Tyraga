def rec(w,k):
    """Запись о свергнутом боссе. В сохранениях до v12 её нет: тогда заводится спокойная запись без обиды и реванша."""
    ex=core.C(w)['ex']
    if k not in ex and core.is_former(w,k):ex[k]={'day':w.s['day'],'by':'раньше','falls':1,'peace':False,'mock':False,'revenge':None,'will':False,'at':w.s['day']+3}
    return ex.get(k)
def word(k):return cast.g(k,'бывший','бывшая')
def label(k):
    """Подпись для журнала и карты: «бывший хозяин двора», «бывшая хозяйка театра»."""
    return '%s %s %s'%(word(k),cast.g(k,'хозяин','хозяйка'),EX[k]['was']) if k in EX else word(k)
def role(w,k):
    """Роль героя для подсказки ИИ. У свергнутого босса к прежнему характеру дописано, кем он стал."""
    base=w.npcs[k]['role']
    if not core.is_former(w,k) or k not in EX:return base
    return base+' Теперь всё иначе. '+EX[k]['role']
def lore(w,k):
    """Что герой k знает о своём падении, реванше и о вернувшихся боссах."""
    out=[];r=rec(w,k)
    if r and core.is_former(w,k):
        if r.get('peace'):out.append('С игроком вы помирились: зла на него не держишь.')
        elif r.get('mock'):out.append('После падения игрок тебя унизил. Ты это запомнил.')
        st=r.get('revenge')
        if st in('due','fight'):out.append('Сегодня ты вызвал игрока на разборку: хочешь вернуть своё место.')
        elif st=='won':out.append('Ты пытался вернуть своё место и проиграл игроку во второй раз. Больше не полезешь.')
        elif st=='off':out.append('От реванша ты отказался.')
    elif r and r.get('revenge')=='back':out.append('Игрок сверг тебя, но ты вернул себе власть. Теперь держишься за неё крепче.')
    for b,rb in core.C(w)['ex'].items():
        if b!=k and rb.get('revenge')=='back' and core.in_power(w,b):out.append('Игрок сверг босса «%s», но не удержал победу: власть вернулась к прежнему хозяину.'%w.npcs[b]['name'])
    return out

# ---------- падение ----------
def on_fall(w,k,by):
    """Запись о свержении. Решает, затаит ли бывший обиду; второй раз свергнутый уже не поднимается."""
    c=core.C(w);d=w.s['day'];old=c['ex'].get(k);falls=(old or {}).get('falls',0)+1
    h=d*7+sum(map(ord,k))  # без общего генератора случайностей: порядок прежних событий не сдвигается
    r={'day':d,'by':by,'falls':falls,'peace':False,'mock':False,'revenge':None,'will':h%5<3,'at':d+3+h%3}
    if falls>1:r.update(will=False,revenge='never')
    c['ex'][k]=r
    if k in FREE and FREE[k][0] in c['done']:core.flag(w,FREE[k][1])
def peace(w,k):
    r=rec(w,k)
    if not r:return []
    r['peace']=True;r['will']=False
    if r.get('revenge') in('due','fight'):r['revenge']='off'
    cn=core.C(w)['counters'];cn['ex_peace']=cn.get('ex_peace',0)+1
    return ['Помирились: %s'%w.npcs[k]['name']]
def mock(w,k,days=2):
    """Унижение или побои после падения: бывший затаил обиду, реванш будет скоро."""
    r=rec(w,k)
    if not r or r.get('revenge') is not None:return []  # реванш уже идёт, был или отменён насовсем
    r['peace']=False;r['mock']=True;r['will']=True;r['at']=min(r['at'],w.s['day']+days)
    return ['%s %s обиду'%(w.npcs[k]['name'],cast.g(k,'затаил','затаила'))]
def off(w,k):
    r=rec(w,k)
    if r:r['revenge']='off';r['will']=False
    return ['Реванша не будет']

# ---------- реванш ----------
def due(w):
    c=core.C(w);return [k for k,r in c['ex'].items() if r.get('revenge')=='due' and k in c['ousted']]
def _queue(w,k):
    c=core.C(w)
    if not any(p.get('id')=='revenge_'+k for p in c['pending']):c['pending'].append({'t':'scene','id':'revenge_'+k})
def morning(w):
    """Утро: обиженный бывший, чей срок подошёл, зовёт на разборку. Не больше одного в день."""
    c=core.C(w);d=w.s['day']
    if not due(w):
        for k,r in c['ex'].items():
            if k in c['ousted'] and r.get('will') and not r.get('peace') and r.get('revenge') is None and d>=r.get('at',d):
                r['revenge']='due';home=w.npcs[k]['home'];name=w.npcs[k]['name']
                w.event('revenge','%s %s игрока на разборку: хочет вернуть себе %s.'%(name,cast.g(k,'вызвал','вызвала'),EX[k]['took']),list(w.npcs),public=True)
                core.say(w,'⚔ %s зовёт на разборку %s. До отбоя не придёте — %s себе %s.'%(name,cast.place_in(home),'вернёт',EX[k]['took']))
                break
    on_enter(w)
def on_enter(w):
    """Игрок в локации бывшего, который ждёт разборки: сцена реванша начинается сразу."""
    for k in due(w):
        if w.npcs[k]['home']==w.s['loc']:_queue(w,k)
def night(w):
    """Отбой: кто ждал разборки и не дождался, возвращает себе власть без боя."""
    c=core.C(w)
    for k,r in list(c['ex'].items()):
        if k in c['ousted'] and r.get('revenge') in('due','fight'):restore(w,k,'неявка')
def revenge_now(w,k):
    r=rec(w,k);return bool(r and r.get('revenge')=='fight' and core.is_former(w,k))
def start_duel(w,k,ambush=False):
    """Бой-реванш: бывший выходит в полную силу. Сам бой запускает интерфейс (очередь событий, тип 'fight')."""
    r=rec(w,k)
    if not r or not core.is_former(w,k):return []
    c=core.C(w);r['revenge']='fight';w.s['npc_health'].pop(k,None)
    c['pending']=[p for p in c['pending'] if p.get('id')!='fight_'+k]
    c['pending'].insert(0,{'t':'fight','id':'fight_'+k,'k':k,'ambush':bool(ambush)})
    return ['Бой за %s'%EX[k]['took']]
def after_duel(w,k,result):
    """Итог боя с бывшим боссом. True — бой обработан здесь, обычные правила драки не нужны."""
    r=rec(w,k)
    if not r or not core.is_former(w,k):return False
    c=core.C(w);cn=c['counters'];name=w.npcs[k]['name']
    if r.get('revenge')=='fight':
        if result=='Победа':
            r['revenge']='won';r['will']=False;cn['revenge_won']=cn.get('revenge_won',0)+1
            w.event('revenge_lost','%s %s вернуть себе %s и снова %s игроку.'%(name,cast.g(k,'пытался','пыталась'),EX[k]['took'],cast.g(k,'проиграл','проиграла')),list(w.npcs),public=True)
            w.s['street_rep']['earned']=min(100,w.s['street_rep']['earned']+4);core.add_caste(w,6,'реванш отбит')
            core.say(w,'⚔ Реванш отбит: %s больше не полезет.'%name)
        else:restore(w,k,'реванш')
        return True
    if result=='Победа':
        # Бить лежачего — не по понятиям: уважения не прибавляет, а обиду растит.
        w.s['karma']['honor']=max(-100,w.s['karma']['honor']-2);w.s['relations'][k]=max(-100,w.s['relations'].get(k,0)-10)
        mock(w,k);core.say(w,'Бить лежачего — не по понятиям: уважения это не прибавило.')
    elif result=='Поражение':
        core.add_caste(w,-8,'проигрыш в драке');mock(w,k,1)
    return True
def restore(w,k,why):
    """Бывший возвращает себе власть: снова босс, его правила снова действуют."""
    c=core.C(w)
    if k not in c['ousted']:return False
    c['ousted'].remove(k);r=c['ex'].setdefault(k,{'falls':1});r.update(revenge='back',will=False,back=w.s['day'])
    if k in FREE:c['flags'].pop(FREE[k][1],None)
    c['pending']=[p for p in c['pending'] if p.get('id') not in('revenge_'+k,'fight_'+k)]
    w.s['npc_health'].pop(k,None);name=w.npcs[k]['name'];cn=c['counters'];cn['boss_back']=cn.get('boss_back',0)+1
    w.event('boss_back','%s %s себе %s: игрок не удержал победу.'%(name,cast.g(k,'вернул','вернула'),EX[k]['took']),list(w.npcs),public=True)
    core.add_caste(w,-8,'%s снова у власти'%name)
    core.say(w,'☠ %s %s себе %s: %s.'%(name,cast.g(k,'вернул','вернула'),EX[k]['took'],'вы не пришли на разборку' if why=='неявка' else 'реванш проигран'))
    return True

